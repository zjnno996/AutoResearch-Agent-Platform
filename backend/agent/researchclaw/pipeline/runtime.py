"""Common stage lifecycle. Business stage implementations live in a registry.

The compatibility executor supplies bindings; this module does not import the
legacy implementation module. Alternative handlers can reuse the lifecycle.
"""

from __future__ import annotations

import logging
import time as _time
import json
from collections.abc import Callable
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from researchclaw.adapters import AdapterBundle
from researchclaw.config import RCConfig
from researchclaw.evaluation.protocol import audit_evaluation_protocol
from researchclaw.llm import create_llm_client
from researchclaw.llm.client import LLMClient
from researchclaw.pipeline.contracts import CONTRACTS, StageContract
from researchclaw.pipeline.models import StageResult
from researchclaw.pipeline.registry import StageRegistry
from researchclaw.pipeline.stages import Stage, StageStatus, TransitionEvent, advance, gate_required
from researchclaw.prompts import PromptManager

logger = logging.getLogger(__name__)


@dataclass(frozen=True)
class StageBindings:
    registry: StageRegistry
    read_artifact: Callable[..., str | None]
    write_metadata: Callable[..., None]
    load_feedback: Callable[..., str]
    llm_client: Any = LLMClient
    client_factory: Callable[..., Any] = create_llm_client
    audit_protocol: Callable[..., dict[str, Any]] = audit_evaluation_protocol


def default_bindings() -> StageBindings:
    """Compose the production runtime without importing the legacy facade."""
    from researchclaw.pipeline.builtins import default_registry
    from researchclaw.pipeline.support.artifacts import _read_prior_artifact, _write_stage_meta
    from researchclaw.pipeline.support.context import _load_human_feedback
    return StageBindings(default_registry(), _read_prior_artifact, _write_stage_meta, _load_human_feedback)


def _utcnow_iso() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def execute_stage_impl(
    stage: Stage,
    *,
    run_dir: Path,
    run_id: str,
    config: RCConfig,
    adapters: AdapterBundle,
    auto_approve_gates: bool = False,
    bindings: StageBindings,
) -> StageResult:
    """Execute one pipeline stage, validate outputs, and apply gate logic."""

    stage_dir = run_dir / f"stage-{int(stage):02d}"
    stage_dir.mkdir(parents=True, exist_ok=True)
    _t_health_start = _time.monotonic()
    contract: StageContract = CONTRACTS[stage]

    if contract.input_files:
        for input_file in contract.input_files:
            found = bindings.read_artifact(run_dir, input_file)
            if found is None:
                result = StageResult(
                    stage=stage,
                    status=StageStatus.FAILED,
                    artifacts=(),
                    error=f"Missing input: {input_file} (required by {stage.name})",
                    decision="retry",
                )
                return _finalize_stage(result, stage_dir, run_dir, run_id, config, bindings, _t_health_start)

    bridge = config.openclaw_bridge
    if bridge.use_message and config.notifications.on_stage_start:
        adapters.message.notify(
            config.notifications.channel,
            f"stage-{int(stage):02d}-start",
            f"Starting {stage.name}",
        )
    if bridge.use_memory:
        adapters.memory.append("stages", f"{run_id}:{int(stage)}:running")

    llm = None
    try:
        if config.llm.provider == "acp":
            llm = bindings.client_factory(config)
        else:
            candidate = bindings.llm_client.from_rc_config(config)
            if candidate.config.base_url and candidate.config.api_key:
                llm = candidate
    except Exception:  # noqa: BLE001
        llm = None

    try:
        _ = advance(stage, StageStatus.PENDING, TransitionEvent.START)
        prompts = PromptManager(config.prompts.custom_file or None)  # type: ignore[attr-defined]

        human_fb = bindings.load_feedback(run_dir, stage)
        if human_fb:
            prompts.set_human_feedback(human_fb)
            logger.info("Stage %s: injecting human feedback (%d chars)", stage.name, len(human_fb))

        result = bindings.registry.invoke(
            stage, stage_dir, run_dir, config, adapters, llm=llm, prompts=prompts
        )
    except Exception as exc:  # noqa: BLE001
        logger.exception("Stage %s failed", stage.name)
        result = StageResult(
            stage=stage,
            status=StageStatus.FAILED,
            artifacts=(),
            error=str(exc),
            decision="retry",
        )

    # Turn the planned evaluation protocol into a persisted, deterministic
    # audit after result analysis.  Downstream export/reporting can consume it
    # without trusting prose generated by the model.
    if stage == Stage.RESULT_ANALYSIS and result.status == StageStatus.DONE:
        try:
            _protocol_audit = bindings.audit_protocol(run_dir, stage_dir)
            if "evaluation_protocol_audit.json" not in result.artifacts:
                result = StageResult(
                    stage=result.stage,
                    status=result.status,
                    artifacts=tuple(result.artifacts) + ("evaluation_protocol_audit.json",),
                    error=result.error,
                    decision=("degraded" if _protocol_audit.get("status") != "passed" else result.decision),
                    evidence_refs=tuple(result.evidence_refs) + ("stage-16/evaluation_protocol_audit.json",),
                )
        except Exception as _audit_exc:  # noqa: BLE001
            logger.warning("Evaluation protocol audit failed: %s", _audit_exc)

    if result.status == StageStatus.DONE:
        for output_file in contract.output_files:
            if output_file.endswith("/"):
                path = stage_dir / output_file.rstrip("/")
                if not path.is_dir() or not any(path.iterdir()):
                    result = StageResult(
                        stage=stage,
                        status=StageStatus.FAILED,
                        artifacts=result.artifacts,
                        error=f"Missing output directory: {output_file}",
                        decision="retry",
                        evidence_refs=result.evidence_refs,
                    )
                    break
            else:
                path = stage_dir / output_file
                if not path.exists() or path.stat().st_size == 0:
                    result = StageResult(
                        stage=stage,
                        status=StageStatus.FAILED,
                        artifacts=result.artifacts,
                        error=f"Missing or empty output: {output_file}",
                        decision="retry",
                        evidence_refs=result.evidence_refs,
                    )
                    break

    if config.research_engine.enabled:
        from researchclaw.orchestration.engine import evaluate_stage
        result = evaluate_stage(run_dir, int(stage), result, config, llm)

    # --- MetaClaw PRM quality gate evaluation ---
    try:
        mc_bridge = getattr(config, "metaclaw_bridge", None)
        if (
            mc_bridge
            and getattr(mc_bridge, "enabled", False)
            and result.status == StageStatus.DONE
        ):
            mc_prm = getattr(mc_bridge, "prm", None)
            if mc_prm and getattr(mc_prm, "enabled", False):
                prm_stages = getattr(mc_prm, "gate_stages", (5, 9, 17, 23))
                if int(stage) in prm_stages:
                    from researchclaw.metaclaw_bridge.prm_gate import ResearchPRMGate

                    prm_gate = ResearchPRMGate.from_bridge_config(mc_prm)
                    if prm_gate is not None:
                        # Read stage output for PRM evaluation
                        output_text = ""
                        for art in result.artifacts:
                            art_path = stage_dir / art
                            if art_path.exists() and art_path.is_file():
                                try:
                                    output_text += art_path.read_text(encoding="utf-8")[:4000]
                                except (UnicodeDecodeError, OSError):
                                    pass
                        if output_text:
                            prm_score = prm_gate.evaluate_stage(int(stage), output_text)
                            logger.info(
                                "MetaClaw PRM score for stage %d: %.1f",
                                int(stage),
                                prm_score,
                            )
                            # Write PRM score to stage health
                            import json as _prm_json

                            prm_report = {
                                "stage": int(stage),
                                "prm_score": prm_score,
                                "model": prm_gate.model,
                                "votes": prm_gate.votes,
                            }
                            (stage_dir / "prm_score.json").write_text(
                                _prm_json.dumps(prm_report, indent=2),
                                encoding="utf-8",
                            )
                            # If PRM score is -1 (fail), mark stage as failed
                            if prm_score == -1.0:
                                logger.warning(
                                    "MetaClaw PRM rejected stage %d output",
                                    int(stage),
                                )
                                result = StageResult(
                                    stage=result.stage,
                                    status=StageStatus.FAILED,
                                    artifacts=result.artifacts,
                                    error="PRM quality gate: output below quality threshold",
                                    decision="retry",
                                    evidence_refs=result.evidence_refs,
                                )
    except Exception:  # noqa: BLE001
        logger.warning("MetaClaw PRM evaluation failed (non-blocking)")

    if result.status == StageStatus.DONE and gate_required(stage, config.security.hitl_required_stages):
        if auto_approve_gates:
            if bridge.use_memory:
                adapters.memory.append("gates", f"{run_id}:{int(stage)}:auto-approved")
        else:
            result = StageResult(
                stage=result.stage,
                status=StageStatus.BLOCKED_APPROVAL,
                artifacts=result.artifacts,
                error=result.error,
                decision="block",
                evidence_refs=result.evidence_refs,
            )
            if bridge.use_message and config.notifications.on_gate_required:
                adapters.message.notify(
                    config.notifications.channel,
                    f"gate-{int(stage):02d}",
                    f"Approval required for {stage.name}",
                )

    if bridge.use_memory:
        adapters.memory.append("stages", f"{run_id}:{int(stage)}:{result.status.value}")

    return _finalize_stage(result, stage_dir, run_dir, run_id, config, bindings, _t_health_start)


def _finalize_stage(result: StageResult, stage_dir: Path, run_dir: Path, run_id: str,
                    config: RCConfig, bindings: StageBindings, started_at: float) -> StageResult:
    stage = result.stage
    from researchclaw.orchestration.engine import record_stage
    result = record_stage(run_dir, int(stage), result, config)
    bindings.write_metadata(stage_dir, stage, run_id, result)

    _t_health_end = _time.monotonic()
    stage_health = {
        "stage_id": f"{int(stage):02d}-{stage.name.lower()}",
        "run_id": run_id,
        "duration_sec": round(_t_health_end - started_at, 2),
        "status": result.status.value,
        "artifacts_count": len(result.artifacts),
        "error": result.error,
        "timestamp": _utcnow_iso(),
    }
    try:
        from researchclaw.orchestration.artifacts import write_json
        write_json(stage_dir / "stage_health.json", stage_health)
    except OSError:
        pass
    try:
        from researchclaw.observability.tracing import trace_event
        trace_event(run_dir / "traces", "stage_result", stage_health)
    except Exception:  # noqa: BLE001
        pass

    return result



def execute_stage(
    stage: Stage,
    *,
    run_dir: Path,
    run_id: str,
    config: RCConfig,
    adapters: AdapterBundle,
    auto_approve_gates: bool = False,
    bindings: StageBindings | None = None,
) -> StageResult:
    """Run a stage with isolated skill context and complete call accounting."""
    from researchclaw.observability.tracing import StageTrace
    from researchclaw.orchestration.context import stage_guidance
    from researchclaw.orchestration.engine import prepare_stage

    bindings = bindings or default_bindings()
    stage_dir = run_dir / f"stage-{int(stage):02d}"
    stage_dir.mkdir(parents=True, exist_ok=True)
    from researchclaw.skills.registry import BUILTIN_ROOT
    read_dirs = (str(BUILTIN_ROOT), *config.research_engine.skills_dirs) if config.research_engine.enabled else ()
    with StageTrace(run_dir, stage_dir, int(stage), stage.name, run_id) as trace:
        with stage_guidance(prepare_stage(run_dir, int(stage), config), read_dirs=read_dirs):
            result = execute_stage_impl(
                stage, run_dir=run_dir, run_id=run_id, config=config,
                adapters=adapters, auto_approve_gates=auto_approve_gates, bindings=bindings,
            )
        trace.finish(status=result.status.value, artifacts_count=len(result.artifacts),
                     error=result.error or "")
        return result
